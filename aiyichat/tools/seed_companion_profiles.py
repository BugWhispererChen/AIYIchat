def _resolve_portrait_dir() -> Path:
    """解析预置定妆照目录路径，兼容源码/Windows onedir/Linux 容器三种环境。"""
    # Windows onedir 冻结模式：exe 位于 AIYIchatService/，资源在 _internal/
    if getattr(sys, "frozen", False):
        base = Path(sys.executable).resolve().parent / "_internal"
        candidate = base / "data" / "preset_portraits"
        if candidate.is_dir():
            return candidate
    # 源码模式 / Linux 容器：tools/ 的上级目录的 data/preset_portraits/
    candidate = Path(__file__).resolve().parent.parent / "data" / "preset_portraits"
    if candidate.is_dir():
        return candidate
    # 回退：相对当前工作目录（容器内 WORKDIR=/app 时有效）
    return Path("data") / "preset_portraits"


