async def _ensure_reference_images(
    repo: ProfileRepository, *, force: bool = False
) -> None:
    """将预置定妆照写入 media 集合，并回填角色的 reference_image_url。

    幂等策略：
    - 角色已有有效的 reference_image_url（媒体存在）则跳过；
    - 媒体文档按内容 sha256 去重，重复执行不产生重复媒体；
    - 用户已修改的角色（updated_at > created_at）仅在 reference_image_url 为空时补齐。
    """
    media_coll = get_database().media
    for slug in _PORTRAIT_SLUGS:
        profile = await repo.find_by_slug(slug)
        if profile is None:
            logger.warning("角色 %s 不存在，跳过定妆照", slug)
            continue

        # 用户已修改且非强制模式：仅当 reference_image_url 为空时才补齐
        if not force and not _should_overwrite(profile):
            if profile.reference_image_url:
                logger.debug("%s 已被用户修改且已有定妆照，跳过", slug)
                continue
            logger.info("%s 已被用户修改，仅补齐空定妆照", slug)

        # 已设置且媒体仍存在：跳过，避免覆盖后台人工换过的定妆照
        if profile.reference_image_url.startswith("/api/media/"):
            media_id = profile.reference_image_url.rsplit("/", 1)[-1]
            try:
                exists = await media_coll.find_one(
                    {"_id": ObjectId(media_id)}, {"_id": 1}
                )
            except Exception:
                exists = None
            if exists:
                logger.info("%s 已有定妆照，跳过", slug)
                continue

        img_path = _PORTRAIT_DIR / f"{slug}.jpg"
        if not img_path.exists():
            logger.warning("未找到 %s 的预置定妆照: %s", slug, img_path)
            continue

        data = img_path.read_bytes()
        digest = hashlib.sha256(data).hexdigest()

        # 内容去重：相同图片已入库则复用其 ID
        existing = await media_coll.find_one({"sha256": digest}, {"_id": 1})
        if existing is not None:
            media_id = str(existing["_id"])
        else:
            result = await media_coll.insert_one({
                "data": data,
                "content_type": "image/jpeg",
                "filename": f"{slug}.jpg",
                "size": len(data),
                "sha256": digest,
                "created_at": datetime.now(timezone.utc),
            })
            media_id = str(result.inserted_id)

        await repo.update(
            slug, PromptProfileUpdate(reference_image_url=f"/api/media/{media_id}")
        )
        logger.info("已入库定妆照 %s -> /api/media/%s", slug, media_id)


async def seed_profiles(*, force: bool = False, manage_db: bool = False) -> None:
    """执行角色 seed（幂等 upsert）并回填预置定妆照。

    供 app.bootstrap lifespan 启动时自动调用，也可独立执行。

    Args:
        force: 为 True 时强制覆盖所有预置角色（含用户已修改的）；
               为 False 时用户已修改的角色仅补齐空定妆照。
        manage_db: 为 True 时自行管理数据库连接（独立执行时使用）；
                   为 False 时使用已存在的数据库连接（lifespan 调用时使用）。
    """
    if manage_db:
        await connect_db()
    repo = ProfileRepository()
    profiles = _build_profiles()
    created, skipped, updated = 0, 0, 0
    for p in profiles:
        existing = await repo.find_by_slug(p.slug)
        if existing is None:
            await repo.upsert_by_slug(p)
            logger.info("已 seed 角色：%s (%s)", p.name, p.slug)
            created += 1
        elif force or _should_overwrite(existing):
            await repo.upsert_by_slug(p)
            logger.info("已更新预置角色：%s (%s)", p.name, p.slug)
            updated += 1
        else:
            logger.info("跳过用户已修改角色：%s (%s)", p.name, p.slug)
            skipped += 1
    await _ensure_reference_images(repo, force=force)
    logger.info(
        "预置角色 seed 完成：新建 %d / 更新 %d / 跳过 %d，共 %d 个",
        created, updated, skipped, len(profiles),
    )
    if manage_db:
        await close_db()


async def main() -> None:
    """CLI 入口：解析 --force 参数后执行 seed。"""
    force = "--force" in sys.argv
    if force:
        logger.info("--force 模式：强制覆盖所有预置角色（含用户已修改的）")
    await seed_profiles(force=force, manage_db=True)


if __name__ == "__main__":
    asyncio.run(main())
